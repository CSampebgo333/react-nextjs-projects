Il était une fois trois ours qui vivaient dans une maison au cœur de la forêt : un grand papa ours, une maman ours de taille moyenne et un tout petit ourson.

Un matin, ils préparèrent du porridge pour le petit-déjeuner, mais il était beaucoup trop chaud pour être mangé. Ils décidèrent donc d'aller se promener dans la forêt pendant qu'il refroidissait.

Pendant leur absence, une petite fille nommée Boucle d'Or arriva devant leur maison. Elle frappa à la porte, mais comme personne ne répondit, elle entra.

Boucle d'Or aperçut trois bols de porridge sur la table. Elle goûta le premier. « Ce porridge est trop chaud ! » dit-elle. Elle goûta le deuxième. « Celui-ci est trop froid ! » Puis elle goûta le troisième. « Celui-ci est parfait ! » Et elle le mangea entièrement.

Ensuite, Boucle d'Or vit trois chaises. Elle s'assit sur la première. « Cette chaise est trop dure ! » Puis sur la deuxième. « Celle-ci est trop molle ! » Enfin, elle s'assit sur la troisième. « Celle-ci est parfaite ! » Mais la petite chaise se cassa sous son poids.

Fatiguée, Boucle d'Or monta à l'étage et trouva trois lits. Le premier était trop dur, le deuxième trop mou, mais le troisième était parfait. Elle s'y allongea et s'endormit aussitôt.

Lorsque les trois ours rentrèrent chez eux, ils remarquèrent que quelqu'un était entré dans leur maison. Ils trouvèrent Boucle d'Or endormie dans le lit du petit ourson. À son réveil, elle vit les trois ours, poussa un cri, sauta par la fenêtre et s'enfuit en courant jusqu'à chez elle. Elle ne revint plus jamais dans la maison des trois ours.
