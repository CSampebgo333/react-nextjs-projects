Pendant ce temps, la tortue continua d'avancer, pas après pas, sans jamais s'arrêter, jusqu'à la ligne d'arrivée.

Les animaux applaudirent si fort la tortue qu'ils réveillèrent le lièvre. Il se leva d'un bond et se remit à courir, mais il était trop tard. La tortue avait déjà franchi la ligne d'arrivée.

Morale : Rien ne sert de courir, il faut partir à point.
