Il était une fois trois petits cochons qui quittèrent la maison de leur mère pour construire chacun leur propre demeure.

Le premier petit cochon rencontra un homme portant une botte de paille. Il lui demanda : « S'il vous plaît, donnez-moi un peu de paille pour construire ma maison. » L'homme accepta, et le petit cochon bâtit une maison de paille.

Peu après, un grand méchant loup arriva et frappa à la porte.

« Petit cochon, petit cochon, laisse-moi entrer ! »

« Non, non, par les poils de mon petit menton ! » répondit le cochon.

« Alors je soufflerai, je soufflerai, et je ferai s'envoler ta maison ! »

Le loup souffla de toutes ses forces et la maison de paille s'écroula. Le premier petit cochon s'enfuit en courant chez son frère.

Le deuxième petit cochon avait construit une maison en bois. Le loup arriva, souffla encore plus fort et détruisit également cette maison. Les deux cochons s'enfuirent alors chez leur troisième frère.

Le troisième petit cochon avait construit une solide maison en briques. Le loup souffla, souffla encore, mais la maison ne bougea pas d'un seul centimètre.

Furieux, le loup décida de descendre par la cheminée. Mais le troisième petit cochon avait placé un grand chaudron d'eau bouillante dans l'âtre. Le loup tomba dedans, poussa un grand cri et s'enfuit sans jamais revenir.

Les trois petits cochons vécurent désormais ensemble dans la maison de briques. Ils comprirent que le travail, la patience et une bonne préparation permettent de surmonter les difficultés.
