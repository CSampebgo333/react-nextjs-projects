Il était une fois un pauvre garçon nommé Jack qui vivait avec sa mère. Ils ne possédaient qu'une seule vache, mais elle ne donnait plus de lait. La mère de Jack lui demanda donc d'aller la vendre au marché.

En chemin, Jack rencontra un étrange vieil homme qui lui proposa d'échanger la vache contre des haricots magiques. « Ces haricots t'apporteront la fortune », lui dit-il. Jack accepta l'échange.

Lorsque Jack rentra chez lui, sa mère se mit en colère. « Quel garçon insensé ! Tu as échangé notre vache contre des haricots ? » Elle jeta aussitôt les haricots par la fenêtre.

Pendant la nuit, un immense haricot magique poussa jusqu'aux nuages. Au matin, Jack grimpa le long de la tige et découvrit un royaume situé très haut dans le ciel. Il y trouva le château d'un géant et y entra discrètement.

L'épouse du géant offrit quelque chose à manger à Jack, mais elle entendit bientôt son mari revenir. « Fee-fi-fo-fum ! Je sens l'odeur d'un petit Anglais ! » rugit le géant.

Jack se cacha et observa le géant compter ses pièces d'or avant de s'endormir. Sans faire de bruit, Jack prit un sac d'or et redescendit le long du haricot.

Jack remonta encore deux fois. La deuxième fois, il rapporta une poule qui pondait des œufs d'or. La troisième fois, il s'empara d'une harpe magique. Mais cette fois, la harpe se mit à crier, et le géant poursuivit Jack jusqu'au haricot.

Jack descendit aussi vite qu'il le put et coupa la tige du haricot avec une hache. Le géant tomba du haut des nuages et ne reparut jamais. Grâce à leur nouvelle fortune, Jack et sa mère vécurent heureux pour toujours.
$$
