Il était une fois une adorable petite fille que tout le monde aimait. Sa grand-mère lui avait offert un petit chaperon de velours rouge. Comme il lui allait à merveille, elle ne portait plus que celui-ci. C'est ainsi qu'on la surnomma le Petit Chaperon rouge.

Un jour, sa mère lui dit : « Viens, Petit Chaperon rouge. Voici un morceau de gâteau et une bouteille de vin. Porte-les à ta grand-mère. Elle est malade et cela lui fera du bien. »

Le Petit Chaperon rouge partit aussitôt. En traversant la forêt, elle rencontra un loup. Comme elle ignorait qu'il était dangereux, elle n'eut pas peur de lui.

« Bonjour, Petit Chaperon rouge », dit le loup.

« Bonjour, monsieur le Loup », répondit-elle poliment.

« Où vas-tu de si bon matin ? »

« Chez ma grand-mère. »

Le loup eut alors une idée. Il courut jusqu'à la maison de la grand-mère et frappa à la porte.

« Qui est là ? » demanda la grand-mère.

« C'est le Petit Chaperon rouge », répondit le loup en imitant la voix de la fillette.

Lorsque le Petit Chaperon rouge arriva, elle trouva sa grand-mère bien étrange.

« Grand-mère, que tu as de grands yeux ! »

« C'est pour mieux te voir, mon enfant. »

« Grand-mère, que tu as de grandes oreilles ! »

« C'est pour mieux t'entendre, mon enfant. »

« Grand-mère, que tu as de grandes dents ! »

« C'est pour mieux te manger ! »

À ces mots, le loup bondit hors du lit.

Heureusement, un chasseur qui passait par là entendit le bruit. Il entra dans la maison, sauva le Petit Chaperon rouge et sa grand-mère, et tous vécurent heureux par la suite.
